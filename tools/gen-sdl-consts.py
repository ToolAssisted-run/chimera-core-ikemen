#!/usr/bin/env python3
"""Writes go/sdl2/sdl/consts.go: the values of the SDL 2 constants the
stand-in sdl package offers, read from SDL's own headers by a C program.

Which constants: every one go-sdl2 declares as C.<name> whose Go name Ikemen
GO's source uses, plus the event types and the key list the stand-in needs.
The values are SDL 2's (zlib licence); only numbers are copied.

usage: tools/gen-sdl-consts.py <go-sdl2 module dir> <Ikemen-GO src dir> <out.go>
(needs SDL 2's development headers, /usr/include/SDL2)"""
import os, re, subprocess, sys, tempfile

mod, src, out = sys.argv[1:4]
decl = re.compile(r'^\s*([A-Z][A-Z0-9_a-z]*)\s+([A-Za-z]+)?\s*=\s*C\.([A-Za-z0-9_]+)')
consts = {}
for f in sorted(os.listdir(os.path.join(mod, "sdl"))):
    if not f.endswith(".go"):
        continue
    typ = None
    for line in open(os.path.join(mod, "sdl", f)):
        m = decl.match(line)
        if m:
            name, t, cname = m.groups()
            consts.setdefault(name, (t or "", cname))
used = set()
# the files a Linux desktop build compiles (not the Android, iOS, macOS,
# Windows or Vulkan ones)
skip = re.compile(r'_(android|ios|darwin|windows)\.go$|^(render_vk|font_vk|render_gles32|font_gles32)')
for f in os.listdir(src):
    if f.endswith(".go") and not skip.search(f):
        used |= set(re.findall(r'sdl\.([A-Z][A-Za-z0-9_]*)', open(os.path.join(src, f)).read()))
wanted = {n for n in consts if n in used or n.startswith("K_") or n.startswith("KMOD_")
          or n in ("KEYDOWN", "KEYUP", "CONTROLLERAXISMOTION", "CONTROLLERBUTTONDOWN", "CONTROLLERBUTTONUP",
                   "CONTROLLERDEVICEADDED", "CONTROLLERDEVICEREMOVED", "QUIT", "WINDOWEVENT", "TEXTINPUT",
                   "JOYDEVICEADDED", "JOYDEVICEREMOVED", "PRESSED", "RELEASED", "QUERY", "IGNORE",
                   "CONTROLLER_BUTTON_INVALID", "CONTROLLER_BUTTON_MAX", "CONTROLLER_AXIS_LEFTX",
                   "CONTROLLER_AXIS_LEFTY", "CONTROLLER_AXIS_RIGHTX", "CONTROLLER_AXIS_RIGHTY",
                   "CONTROLLER_AXIS_INVALID", "CONTROLLER_AXIS_MAX", "FIRSTEVENT", "LASTEVENT")
          or n.startswith("SCANCODE_")}
names = sorted(wanted)
prog = ['#include <SDL2/SDL.h>', '#include <stdio.h>', 'int main(void) {']
for n in names:
    t, c = consts[n]
    if c.startswith("SDL_HINT_"):  # a string
        prog.append(f'printf("%s \\"%s\\"\\n", "{n}", {c});')
    else:
        prog.append(f'printf("%s %lld\\n", "{n}", (long long)({c}));')
prog.append('return 0; }')
with tempfile.TemporaryDirectory() as d:
    open(f"{d}/c.c", "w").write("\n".join(prog))
    subprocess.check_call(["gcc", "-o", f"{d}/c", f"{d}/c.c"])
    values = dict(l.split(None, 1) for l in subprocess.check_output([f"{d}/c"]).decode().splitlines())
undeclared = sorted(n for n in used if n not in consts)
with open(out, "w") as o:
    o.write("// Code generated by tools/gen-sdl-consts.py from SDL 2's headers; DO NOT EDIT.\n\n")
    o.write("package sdl\n\nconst (\n")
    for n in names:
        t = consts[n][0]
        o.write(f"\t{n} {t} = {values[n]}\n" if t else f"\t{n} = {values[n]}\n")
    o.write(")\n")
print(f"{len(names)} constants; names used that are not constants:", " ".join(undeclared))
